export const INCOTERM_HINTS: Record<string, string> = Object.fromEntries(
  INCOTERM_OPTIONS.map(({ code, hint }) => [code, hint]),
);

export const isReferenceIncoterm = (code: string): boolean =>
  code in INCOTERM_HINTS;

// Свой базис закупщика. Проверка здесь только для того, чтобы не
// отправлять на сервер заведомо негодное и сразу сказать почему;
// последнее слово всё равно за сервером — правило живёт там
// (app/services/incoterms.py, CUSTOM_INCOTERM_MAX_LENGTH).
export const CUSTOM_INCOTERM_MAX_LENGTH = 24;
const CUSTOM_INCOTERM_RE = /^[A-ZА-ЯЁ][A-ZА-ЯЁ0-9 ./-]{1,23}$/;

/** Свой базис в том виде, в каком он уйдёт на сервер, или null. */
export const normalizeCustomIncoterm = (value: string): string | null => {
  const code = value.trim().split(/\s+/).join(" ").toUpperCase();
  return CUSTOM_INCOTERM_RE.test(code) ? code : null;
};
