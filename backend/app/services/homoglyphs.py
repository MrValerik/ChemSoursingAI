"""Кириллические буквы, притворяющиеся латинскими.

Запрос #31 «С18-С22 fatty alcohol» упал: поиск вернул ноль на все восемь
запросов подряд, и система списала это на блокировку поисковика. На деле
«С» в «С18-С22» — кириллическая U+0421, а не латинская C. Выглядят они
одинаково, но для поисковика это разные строки, а имя во всех запросах
стоит в кавычках как точная фраза — потому и ноль.

Проверено: тот же запрос с латинской буквой находит китайских
поставщиков пачками.

Берётся это из документов заказчика: половина списка сырья набрана в
Word и Excel, где раскладка переключается на полуслове. Ту же беду мы уже
чинили с дефисами в CAS-номерах — здесь она же, только с буквами.

Правило намеренно узкое: правятся только слова, где кириллица и латиница
перемешаны. Целиком русское название — «Ацетилсалициловая кислота» —
остаётся нетронутым, иначе мы сломаем половину справочника.
"""

from __future__ import annotations

import re

# Кириллические буквы, неотличимые от латинских на вид.
_LOOKALIKES = {
    "А": "A", "В": "B", "Е": "E", "К": "K", "М": "M", "Н": "H",
    "О": "O", "Р": "P", "С": "C", "Т": "T", "У": "Y", "Х": "X",
    "а": "a", "в": "b", "е": "e", "к": "k", "м": "m", "н": "h",
    "о": "o", "р": "p", "с": "c", "т": "t", "у": "y", "х": "x",
    "і": "i", "ѕ": "s", "ј": "j", "Ј": "J", "І": "I", "Ѕ": "S",
    "ԁ": "d", "ԛ": "q", "ԝ": "w", "Ԍ": "G",
}
_LOOKALIKE_TABLE = str.maketrans(_LOOKALIKES)

_CYRILLIC = re.compile(r"[А-Яа-яЁёІіЈјЅѕԁԛԝԌ]")
_LATIN = re.compile(r"[A-Za-z]")
_DIGIT = re.compile(r"\d")
# Слово — то, что разделено пробелами. Дефисы внутри слова не разрывают
# его: «С18-С22» должно чиниться целиком.
_WORD = re.compile(r"\S+")


def _fix_word(word: str, *, latin_context: bool) -> str:
    if not _CYRILLIC.search(word):
        return word

    # Кириллица вплотную к латинице в одном слове — опечатка всегда:
    # «Сtearyl» настоящим словом быть не может ни в каком языке.
    mixed_letters = bool(_LATIN.search(word))

    # Кириллица с цифрой и без латиницы — «С22» или «А2» — сама по себе
    # неоднозначна: обозначение марки по-русски выглядит так же. Решает
    # окружение: рядом с латинскими словами это опечатка, в чисто русской
    # строке — нет.
    mixed_with_digits = bool(_DIGIT.search(word)) and latin_context

    if not (mixed_letters or mixed_with_digits):
        return word

    fixed = word.translate(_LOOKALIKE_TABLE)
    # Если кириллица осталась, слово было настоящим русским — «ГОСТ2016»:
    # заменить удалось не всё, значит трогать его не за что.
    return word if _CYRILLIC.search(fixed) else fixed


def fix_lookalikes(value: str) -> str:
    """Чинит кириллицу, набранную вместо латиницы, не трогая русский текст."""
    if not value:
        return value
    # Есть ли в строке слово, целиком набранное латиницей: «fatty alcohol»
    # рядом с «С18-С22» и выдаёт опечатку.
    latin_context = any(
        _LATIN.search(word) and not _CYRILLIC.search(word)
        for word in _WORD.findall(value)
    )
    return _WORD.sub(
        lambda m: _fix_word(m.group(0), latin_context=latin_context), value
    )


def has_lookalikes(value: str) -> bool:
    """Есть ли в строке кириллица, притворяющаяся латиницей."""
    return fix_lookalikes(value) != (value or "")
