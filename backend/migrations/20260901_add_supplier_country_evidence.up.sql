-- Доказанная страна поставщика отдельно от запрошенной.
--
-- Поле suppliers.country до сих пор заполнялось страной из формы поиска:
-- «Китай» означало «найдено, когда искали по Китаю», а не «компания
-- находится в Китае». Замер на боевой базе: 279 записей, у всех страна
-- проставлена, и 253 из них — «Китай» просто потому, что столько было
-- поисков по Китаю. Фильтровать поиск по такому полю значит подтверждать
-- собственное допущение.
--
-- Доказательство при этом уже считается на квалификации — country_status
-- со свидетельством вида «прямо указано» или «косвенно, по домену», — и
-- до реестра не доезжало.
ALTER TABLE suppliers
    ADD COLUMN IF NOT EXISTS country_status VARCHAR(16),
    ADD COLUMN IF NOT EXISTS country_evidence VARCHAR(500);

CREATE INDEX IF NOT EXISTS ix_suppliers_country_status
    ON suppliers (country_status);
