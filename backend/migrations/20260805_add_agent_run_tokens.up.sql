-- вызовов, то есть заплатив за замер второй раз. Замер на карбомере через
-- такой повтор: семь вызовов, 20 722 входных токена и 4 753 выходных.
--
-- Вход дороже выхода вчетверо по объёму, поэтому экономия сидит в том, что
-- мы отправляем модели, а не в том, что она отвечает.

