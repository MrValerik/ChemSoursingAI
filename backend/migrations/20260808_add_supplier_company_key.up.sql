-- Ключ для схлопывания дублей поставщика.
--
-- Дедупликация шла по адресу страницы, поэтому одна компания на трёх
-- площадках давала три записи: по реестру 182 поставщика при 159
-- различных компаниях, то есть 23 лишние строки. Hangzhou Leap Chem
-- лежала четырьмя, Jiangsu Honon и TNJ Chemical — тремя, и контакт при
-- этом садился только на одну из них: в таблице отбора остальные строки
-- бесполезны.
--
-- Ключ пишется приложением: нормализация имени (регистр, разделители,
-- юридические хвосты) одинаковее выражается на Python, чем на SQL.
ALTER TABLE suppliers ADD COLUMN IF NOT EXISTS company_key VARCHAR(255);

CREATE INDEX IF NOT EXISTS ix_suppliers_company_key
    ON suppliers (company_key);
