-- Номер лицензии ICP как отдельное поле поставщика.
--
-- Это регистрационный идентификатор сайта, размещённого в материковом
-- Китае: выдаётся министерством и печатается в подвале страницы. Закупщик
-- сверяет его сам на beian.miit.gov.cn — то есть это проверяемый факт о
-- регистрации, а не заявление продавца о себе.
--
-- Замер по 226 сохранённым страницам прогонов 280-312: лицензия нашлась на
-- восемнадцати, а единый код кредитоспособности (USCC), по которому ищет
-- сам реестр, — ни на одной. Поэтому храним то, что есть.
--
-- Поле пригодится и позже: когда появится доступ к торговому реестру,
-- ответ будет цепляться именно к этому идентификатору.
ALTER TABLE suppliers
    ADD COLUMN IF NOT EXISTS icp_licence VARCHAR(64);

CREATE INDEX IF NOT EXISTS ix_suppliers_icp_licence
    ON suppliers (icp_licence);
